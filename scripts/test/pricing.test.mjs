import assert from "node:assert/strict";
const P = await import(new URL("../../lib/pricing.ts", import.meta.url).href);
const { formatCount, formatTry, totalKurus, UNIT_PRICE_KURUS, RELEASE_QTY, QUANTITY_PRESETS } = P;
assert.equal(UNIT_PRICE_KURUS, 1000);
assert.deepEqual([...QUANTITY_PRESETS], [50, 100, 200, 500, 5000]);
assert.equal(RELEASE_QTY.min, 20);
assert.equal(totalKurus(20), 20000);
assert.equal(totalKurus(19), null);
assert.equal(totalKurus(20.5), null);
assert.equal(totalKurus(null), null);
assert.equal(totalKurus(100001), null);
assert.equal(totalKurus(5000), 5_000_000);
assert.equal(formatCount(5000, "tr"), "5.000");
assert.equal(formatCount(5000, "en"), "5,000");
assert.equal(formatCount(5000, "ru"), "5 000");
assert.equal(formatCount(100000, "tr"), "100.000");
assert.equal(formatCount(999, "tr"), "999");
assert.equal(formatTry(1000, "tr"), "10 TL");
assert.equal(formatTry(1000, "en"), "₺10");
assert.equal(formatTry(1000, "ru"), "10 ₺");
assert.equal(formatTry(5_000_000, "tr"), "50.000 TL");
assert.equal(formatTry(1050, "tr"), "10,50 TL");
assert.equal(formatTry(1005, "en"), "₺10.05");
console.log("✓ pricing testleri geçti");
